#!/usr/bin/env python3
"""Generate native/navigation_positions.h from the frozen positions.json.

The frozen FrozenOpponentWrapper samples navigation targets from the
``grounded_positions`` list of positions.json.  The closed-loop native tick
needs that table as constants.  Values are emitted with repr() so every
double round-trips exactly; the source file hash is embedded so a verifier
can refuse a table that does not match the payload it is checked against.
"""
from __future__ import annotations

if __name__ == "__main__" and not __package__:
    import sys as _sys
    from pathlib import Path as _Path
    _sys.path.insert(0, str(_Path(__file__).resolve().parents[2]))


from ai2.paths import REPO_ROOT as PROJECT_ROOT

import argparse
import hashlib
import json
from pathlib import Path

ROOT = PROJECT_ROOT
DEFAULT_OUTPUT = ROOT / "native" / "navigation_positions.h"


def render(positions_path: Path) -> str:
    raw = positions_path.read_bytes()
    data = json.loads(raw)
    points = [(float(p["x"]), float(p["y"])) for p in data["grounded_positions"]]
    if not points:
        raise ValueError("positions.json has no grounded_positions")
    lines = [
        "#ifndef AI2_NAVIGATION_POSITIONS_H",
        "#define AI2_NAVIGATION_POSITIONS_H",
        "/* Generated by navigation_positions_header.py from positions.json; do not edit. */",
        f'#define AI2N_POSITIONS_SHA256 "{hashlib.sha256(raw).hexdigest()}"',
        f"#define AI2N_POSITIONS_COUNT {len(points)}",
        "#define AI2N_POSITIONS_INIT { \\",
    ]
    for x, y in points:
        lines.append(f"    {{{x!r}, {y!r}}}, \\")
    lines += [
        "}",
        "#ifdef __CUDACC__",
        "__constant__ double AI2N_POSITIONS_DEVICE[AI2N_POSITIONS_COUNT][2] = AI2N_POSITIONS_INIT;",
        "static const double AI2N_POSITIONS_HOST[AI2N_POSITIONS_COUNT][2] = AI2N_POSITIONS_INIT;",
        "__host__ __device__ static inline double ai2n_position(int i, int j) {",
        "#if defined(__CUDA_ARCH__)",
        "    return AI2N_POSITIONS_DEVICE[i][j];",
        "#else",
        "    return AI2N_POSITIONS_HOST[i][j];",
        "#endif",
        "}",
        "#else",
        "static const double AI2N_POSITIONS[AI2N_POSITIONS_COUNT][2] = AI2N_POSITIONS_INIT;",
        "static inline double ai2n_position(int i, int j) { return AI2N_POSITIONS[i][j]; }",
        "#endif",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("positions", type=Path)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    text = render(args.positions)
    args.output.write_text(text, encoding="utf-8")
    print(json.dumps({"output": str(args.output), "bytes": len(text)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
